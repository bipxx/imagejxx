"""Transcribe full scalar dataset inputs/outputs from the pinned Java corpus."""
import argparse
import gzip
import hashlib
import json
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORPUS = ROOT / 'docs/parity/reviews/G034-imagej-z-projection-reference001/observations.jsonl.gz'
TARGET = ROOT / 'tests/native/imagej_dataset_projection_reference.inc'
SHA256 = 'a22ae856cac15d0f956f935dbe371136da455e428907590b3040d7c7996f7073'


def shape(image):
    x, y, c, z, t = image['dimensions_xyczt']
    return '{%d,%d,%d,%d,%d,1}' % (t, c, z, y, x)


def planes(image):
    """Reorder Java t,z,c plane storage to dataset t,c,z, without arithmetic."""
    _, _, channels, slices, frames = image['dimensions_xyczt']
    size = image['bit_depth'] // 8
    result = []
    for t in range(frames):
        for c in range(channels):
            for z in range(slices):
                raw = bytes.fromhex(image['planes'][(t*slices+z)*channels+c]['raw_le_hex'])
                codes = [int.from_bytes(raw[i:i+size], 'little')
                         for i in range(0, len(raw), size)]
                result.append('{' + ','.join(f'0x{v:08x}U' for v in codes) + '}')
    return '{' + ','.join(result) + '}'


def calibration(image):
    cal = image['calibration']
    def doubles(key):
        return [struct.unpack('>d', bytes.fromhex(v))[0] for v in cal[key]]
    spacing = doubles('spacing_f64')
    origins = doubles('origin_indices_f64')
    # Convert ImageJ voxel-origin indices to Dataset's world origin convention.
    origin = [-i*s for i, s in zip(origins, spacing)]
    return '{' + ','.join(repr(v) for v in spacing + origin) + '}'


def render():
    data = CORPUS.read_bytes()
    if hashlib.sha256(data).hexdigest() != SHA256:
        raise ValueError('Pinned ImageJ projection corpus changed')
    methods = dict(avg='mean', max='maximum', min='minimum', sum='sum',
                   sd='stddev', median='median')
    types = {8:'UInt8', 16:'UInt16', 32:'Float32'}
    lines = ['// Generated by scripts/generate_imagej_dataset_projection_fixture.py.',
             '// Corpus SHA256: ' + SHA256,
             '// Output values are transcribed, not computed by the target or Python.']
    cases = 0
    for row in map(json.loads, gzip.decompress(data).splitlines()):
        if row['kind'] == 'rgb' or row['expected_outcome'] != 'ok':
            continue
        before, output = row['before'], row['output_api']
        calibrated_output = row.get('output_after_plugin_calibration_steps', output)
        signed = before['calibration']['density_function'] == 0
        first, last = row['bounds_one_based']
        c, _, t = before['position_czt']
        lines.append('{"%s", %s, %s, PixelType::%s, PixelType::%s, "%s", '
                     '%d,%d,%d,%d,%d,%s,%s, %s,%s, %s,%s},' %
                     (row['case_id'], shape(before), shape(output),
                      types[before['bit_depth']], types[output['bit_depth']],
                      methods[row['method']], first-1, last-1, row['group_size'],
                      t-1, c-1, str(row['all_time_frames']).lower(), str(signed).lower(),
                      calibration(before), calibration(calibrated_output),
                      planes(before), planes(output)))
        cases += 1
    assert cases == 228, cases
    return ('\n'.join(lines) + '\n').encode('ascii')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if TARGET.read_bytes() != expected:
            raise SystemExit('Dataset fixture differs from pinned corpus transcription')
    else:
        TARGET.write_bytes(expected)
