"""Transcribe pinned channel/density inputs and outputs without target execution."""
import argparse
import gzip
import hashlib
import json
from pathlib import Path
import runpy

ROOT=Path(__file__).resolve().parents[1]
BASE=ROOT/'docs/parity/reviews/G034-imagej-projection-policy-reference001'
TARGET=ROOT/'tests/native/imagej_projection_policy_reference.inc'
GZIP_SHA='8071289ed0a18f8f93ff678694e0baab0ab143d7a6bcdde76dba7cbc6f606377'
RAW_SHA='683bf512ba10787f4f3ae862a5005a6092df046ce4f0691de30136fa13630139'
CONTRACT_SHA='e4ecfa0b10975ae16943bad8115380466a8f91d88c00fc8cc842c3e2e810b584'


def checked(path,expected):
    raw=path.read_bytes()
    if hashlib.sha256(raw).hexdigest()!=expected:raise ValueError('Pinned policy input changed: '+str(path))
    return raw


def rows():
    contract=json.loads(checked(BASE/'contract.json',CONTRACT_SHA))
    paths={'ObserveProjectionPolicy.java':'tests/reference/ObserveProjectionPolicy.java',
           'ObserveScientificZProjection.java':'tests/reference/ObserveScientificZProjection.java',
           'capture_projection_policy_reference.py':'scripts/capture_projection_policy_reference.py',
           'capture_z_projection_reference.py':'scripts/capture_z_projection_reference.py'}
    seen=set()
    for entry in contract['source_identities']:
        name=entry['path'].replace('\\','/').rsplit('/',1)[1]
        checked(ROOT/paths[name],entry['sha256']);seen.add(name)
    if seen!=set(paths) or contract['ui_executed'] is not False:raise ValueError('Policy source identity/scope differs')
    raw=gzip.decompress(checked(BASE/'observations.jsonl.gz',GZIP_SHA))
    if hashlib.sha256(raw).hexdigest()!=RAW_SHA:raise ValueError('Policy raw identity differs')
    capture=runpy.run_path(str(ROOT/'scripts/capture_projection_policy_reference.py'))
    return capture['decode_rows'](raw)


def shape(image):
    x,y,c,z,t=image['dimensions_xyczt'];s=3 if image['bit_depth']==24 else 1
    return '{%d,%d,%d,%d,%d,%d}'%(t,c,z,y,x,s)


def planes(image):
    x,y,channels,slices,frames=image['dimensions_xyczt'];size={8:1,16:2,24:4,32:4}[image['bit_depth']]
    result=[]
    for t in range(frames):
        for c in range(channels):
            for z in range(slices):
                raw=bytes.fromhex(image['planes'][(t*slices+z)*channels+c]['raw_le_hex'])
                if len(raw)!=x*y*size:raise ValueError('Policy plane byte count differs')
                result.append('{'+','.join(f'0x{int.from_bytes(raw[i:i+size],"little"):08x}U' for i in range(0,len(raw),size))+'}')
    return '{'+','.join(result)+'}'


def render():
    calibration=runpy.run_path(str(ROOT/'scripts/generate_imagej_dataset_projection_fixture.py'))['calibration']
    methods=dict(avg='mean',max='maximum',min='minimum',sum='sum',sd='stddev',median='median')
    types={8:'UInt8',16:'UInt16',24:'UInt8',32:'Float32'}
    lines=['// Generated by scripts/generate_projection_policy_fixture.py.',
           '// Pinned gzip SHA256: '+GZIP_SHA,
           '// Pixel expectations and used table words are transcribed, never calculated by the target.']
    for row in rows():
        before,out=row['before'],row['output_api'];first,last=row['bounds_one_based'];c,_,t=before['position_czt']
        entries='{'+','.join('{%d,0x%sU}'%(e['code'],e['bits']) for e in row['table_entries_used'])+'}'
        keep=out['calibration']['density_function']!=20
        lines.append('{"%s",%s,%s,PixelType::%s,PixelType::%s,"%s",%d,%d,%d,%d,%d,%s,%s,%s,%s,%s,%s,%s,%s},'%
                     (row['case_id'],shape(before),shape(out),types[before['bit_depth']],types[out['bit_depth']],methods[row['method']],
                      first-1,last-1,row['group_size'],t-1,c-1,str(row['kind']=='rgb').lower(),str(row['signed16']).lower(),str(keep).lower(),
                      calibration(before),calibration(row.get('output_after_plugin_calibration_steps',out)),entries,planes(before),planes(out)))
    return ('\n'.join(lines)+'\n').encode('ascii')


if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args();data=render()
    if args.check:
        if TARGET.read_bytes()!=data:raise SystemExit('Policy fixture differs from pinned transcription')
    else:TARGET.write_bytes(data)
