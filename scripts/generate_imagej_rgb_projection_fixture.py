"""Transcribe packed RGB words from pinned ImageJ observations, never target code."""
import argparse
import gzip
import hashlib
import json
from pathlib import Path
import runpy

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT/'tests/native/imagej_rgb_projection_reference.inc'
ORIGINAL = ROOT/'docs/parity/reviews/G034-imagej-z-projection-reference001/observations.jsonl.gz'
SUPPLEMENT = ROOT/'docs/parity/reviews/G034-imagej-rgb-projection-reference001'
ORIGINAL_SHA = 'a22ae856cac15d0f956f935dbe371136da455e428907590b3040d7c7996f7073'
GZIP_SHA = '6c91f2cea20644dd6ca5fdf390ad75a445731674e6a6d1398d7cfea37aa34dd8'
RAW_SHA = 'ec0a4d16df5dca743af08a689c5c328263036bf22f1cf405347d6c845dfc7cf2'
CONTRACT_SHA = '31db05de544ca8cb3d1e2879ab97a397d33f40f2e84c48419d85a4b544e18fe3'


def checked(path, expected):
    raw = path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != expected:
        raise ValueError('Pinned RGB reference input changed: '+str(path))
    return raw


def supplemental_rows():
    contract = json.loads(checked(SUPPLEMENT/'contract.json', CONTRACT_SHA))
    locations = {'ObserveRGBProjection.java':'tests/reference/ObserveRGBProjection.java',
                 'ObserveScientificZProjection.java':'tests/reference/ObserveScientificZProjection.java',
                 'capture_rgb_projection_reference.py':'scripts/capture_rgb_projection_reference.py',
                 'capture_z_projection_reference.py':'scripts/capture_z_projection_reference.py'}
    seen = set()
    for entry in contract['source_identities']:
        name = entry['path'].replace('\\','/').rsplit('/',1)[1]
        checked(ROOT/locations[name], entry['sha256'])
        seen.add(name)
    if seen != set(locations) or contract['ui_executed'] is not False:
        raise ValueError('RGB observer identity/scope differs')
    raw = gzip.decompress(checked(SUPPLEMENT/'observations.jsonl.gz', GZIP_SHA))
    if hashlib.sha256(raw).hexdigest() != RAW_SHA:
        raise ValueError('RGB raw observation identity differs')
    capture = runpy.run_path(str(ROOT/'scripts/capture_rgb_projection_reference.py'))
    return capture['decode_rows'](raw)


def shape(image):
    x,y,c,z,t = image['dimensions_xyczt']
    return '{%d,%d,%d,%d,%d,3}' % (t,c,z,y,x)


def planes(image):
    """ARGB32 little-endian words, reordered t,z,c -> t,c,z, not color arithmetic."""
    x,y,channels,slices,frames = image['dimensions_xyczt']
    result = []
    for t in range(frames):
        for c in range(channels):
            for z in range(slices):
                raw = bytes.fromhex(image['planes'][(t*slices+z)*channels+c]['raw_le_hex'])
                if len(raw) != x*y*4:
                    raise ValueError('RGB word count differs')
                words = [int.from_bytes(raw[i:i+4],'little') for i in range(0,len(raw),4)]
                if any(w >> 24 != 255 for w in words):
                    raise ValueError('Unexpected RGB alpha word')
                result.append('{'+','.join(f'0x{w:08x}U' for w in words)+'}')
    return '{'+','.join(result)+'}'


def render():
    old = [r for r in map(json.loads,gzip.decompress(checked(ORIGINAL,ORIGINAL_SHA)).splitlines())
           if r['kind']=='rgb']
    extra = supplemental_rows()
    if len(old)!=96 or len(extra)!=124:
        raise ValueError('RGB case membership changed')
    calibration = runpy.run_path(str(ROOT/'scripts/generate_imagej_dataset_projection_fixture.py'))['calibration']
    methods = dict(avg='mean',max='maximum',min='minimum',sum='sum',sd='stddev',median='median')
    lines = ['// Generated by scripts/generate_imagej_rgb_projection_fixture.py.',
             '// Original gzip SHA256: '+ORIGINAL_SHA, '// Supplemental gzip SHA256: '+GZIP_SHA,
             '// Expected packed words are transcribed from Java, not computed here.']
    for row in old+extra:
        before=row['before'];accepted=row['expected_outcome']=='ok'
        if not accepted and (row['exception']!='java.lang.IllegalArgumentException'
                             or row['message']!='RGB stacks not supported'):
            raise ValueError('RGB negative outcome changed')
        output=row['output_api'] if accepted else before
        expected_cal=row.get('output_after_plugin_calibration_steps',output)
        first,last=row['bounds_one_based'];c,_,t=before['position_czt']
        clip=before['clip_when_summing']=='true'
        lines.append('{"%s",%s,%s,"%s",%d,%d,%d,%d,%d,%s,%s,%s,%s,%s,%s,%s},' %
                     (row['case_id'],shape(before),shape(output),methods[row['method']],
                      first-1,last-1,row['group_size'],t-1,c-1,
                      str(row['all_time_frames']).lower(),str(clip).lower(),str(accepted).lower(),
                      calibration(before),calibration(expected_cal),
                      planes(before) if accepted else '{}',planes(output) if accepted else '{}'))
    return ('\n'.join(lines)+'\n').encode('ascii')


if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    data=render()
    if args.check:
        if TARGET.read_bytes()!=data:
            raise SystemExit('RGB fixture differs from pinned observation transcription')
    else:
        TARGET.write_bytes(data)
