def _archived_producer_source_bytes(root, pin, run, where, result, kind, **identities):
    """Read a member only from this accepted run's exact source freeze."""
    if kind not in {"sources", "artifacts"}:
        return None
    identity = run.get("identity", {})
    if not isinstance(identity, dict) or "source_freeze" not in identity:
        return None
    workspace = Path(root).resolve()

    def guarded_bytes(relative, expected_sha, expected_size, label, snapshot=None):
        schema.path(relative, where)
        member = workspace / relative
        for node in (member, *member.parents):
            if not node.is_relative_to(workspace):
                schema.fail(where, label + " escapes workspace")
            if node.is_symlink() or getattr(node, "is_junction", lambda: False)():
                schema.fail(where, label + " contains an aliased path")
            if node == workspace:
                break
        member = member.resolve()
        if not member.is_relative_to(workspace):
            schema.fail(where, label + " escapes workspace")
        if snapshot is not None:
            directory = (workspace / snapshot).resolve()
            if not directory.is_relative_to(workspace) or not member.is_relative_to(directory):
                schema.fail(where, "historical source snapshot escapes declared directory")
            if not directory.is_dir():
                schema.fail(where, "pinned historical source snapshot bytes are unavailable")
        if not member.is_file():
            schema.fail(where, "pinned " + label + " bytes are unavailable")
        data = member.read_bytes()
        if hashlib.sha256(data).hexdigest() != expected_sha:
            schema.fail(where, label + " byte fingerprint changed")
        if expected_size is not None:
            schema.number(expected_size, where, integer=True)
            if expected_size != len(data):
                schema.fail(where, label + " byte count changed")
        return member, data

    freeze_pin = identity["source_freeze"]
    execution.file_identity(freeze_pin, where)
    _, freeze_bytes = guarded_bytes(freeze_pin["path"], freeze_pin["sha256"],
                                    freeze_pin.get("bytes"), "source freeze")
    freeze = schema.obj(execution.strict_json(freeze_bytes, where), where)
    schema.version(freeze.get("schema_version"), where)
    sources = schema.obj(freeze.get("sources"), where)
    for path, expected_sha in sources.items():
        schema.path(path, where)
        schema.sha(expected_sha, where)
    schema.path(freeze.get("source_snapshot"), where)
    snapshot = freeze["source_snapshot"]
    expected_sha = sources.get(pin["path"])
    if expected_sha is None:
        return None  # Retained tooling rules still apply outside source membership.
    if expected_sha != pin["sha256"]:
        schema.fail(where, "producer/source freeze member fingerprint differs")
    member, data = guarded_bytes((PurePosixPath(snapshot) / pin["path"]).as_posix(),
                                 expected_sha, pin.get("bytes"), "historical source snapshot", snapshot)
    result.setdefault("archived_sources", []).append({
        **identities, "kind": "producer_source" if kind == "sources" else "producer_artifact",
        "path": pin["path"], "snapshot_path": member.relative_to(workspace).as_posix(),
        "sha256": expected_sha, "bytes": len(data), "source_freeze": deepcopy(freeze_pin),
    })
    return data


def _producer_bytes(root, pin, run, producer, where, result, kind, **identities):
    """Resolve the original proof adapter only through its accepted tooling chain."""
    execution.file_identity(pin, where)
    data = evidence.historical_evidence_bytes(root, pin["path"], where)
    if data is not None and hashlib.sha256(data).hexdigest() == pin["sha256"]:
        return _bytes(root, pin, where, result, "producer_" + kind, **identities)
    archived = _archived_producer_source_bytes(root, pin, run, where, result, kind, **identities)
    if archived is not None:
        return archived
    stored = execution.stored_evidence_tool_source(root, pin, "producer_artifact" if kind == "artifacts" else "producer_source", where, result, **identities)
    if stored is not None:
        return stored
    logical = "scripts/parity_fixtures.py"
    archived_path = "build/plan-implementation/p05f-axis-plane-export-001/source-preparation-019/scripts/parity_fixtures.py"
    identity = run.get("identity", {})
    if kind != "sources" or pin["path"] != logical or not isinstance(identity, dict) or "configuration" not in identity:
        return _bytes(root, pin, where, result, "producer_" + kind, **identities)
    workspace = Path(root).resolve()

    def original_bytes(original_pin):
        execution.file_identity(original_pin, where)
        size = _integer(original_pin.get("bytes"), where, 0, 2 * 1024 * 1024)
        member = workspace / original_pin["path"]
        for node in (member, *member.parents):
            if not node.is_relative_to(workspace):
                schema.fail(where, "archived tool source escapes workspace")
            if node.is_symlink() or getattr(node, "is_junction", lambda: False)():
                schema.fail(where, "archived tool source contains an aliased path")
            if node == workspace:
                break
        member = member.resolve()
        if not member.is_relative_to(workspace) or not member.is_file():
            schema.fail(where, "pinned original tooling bytes are unavailable")
        data = member.read_bytes()
        if len(data) != size or hashlib.sha256(data).hexdigest() != original_pin["sha256"]:
            schema.fail(where, "pinned original tooling byte identity changed")
        return data

    configuration_pin = identity["configuration"]
    configuration = execution.strict_json(original_bytes(configuration_pin), where)
    helper_pin = schema.obj(configuration.get("helper"), where)
    if not any(execution.same(helper_pin, item) for item in producer["sources"]):
        schema.fail(where, "original configuration helper differs from accepted producer source")
    helper_bytes = original_bytes(helper_pin)
    try:
        tree = ast.parse(helper_bytes.decode("utf-8"))
        assignments = [node.value for node in tree.body if isinstance(node, ast.Assign)
                       and any(isinstance(name, ast.Name) and name.id == "PINS" for name in node.targets)]
        if len(assignments) != 1:
            schema.fail(where, "original tooling requires one literal PINS mapping")
        tooling = schema.obj(ast.literal_eval(assignments[0]), where)
    except (SyntaxError, UnicodeError, ValueError, TypeError) as error:
        schema.fail(where, f"original tooling PINS mapping is not a literal: {error}")
    tool_pin = schema.obj(tooling.get("adapter"), where)
    if set(tool_pin) != {"path", "sha256", "bytes"} or tool_pin.get("path") != archived_path:
        schema.fail(where, "original tooling adapter is not the listed sealed source member")
    if tool_pin.get("sha256") != pin["sha256"] or "bytes" in pin and tool_pin.get("bytes") != pin["bytes"]:
        schema.fail(where, "original tooling adapter mapping differs from accepted live source")
    data = original_bytes(tool_pin)
    result.setdefault("archived_tool_sources", []).append({
        **identities, "kind": "archived_tool_source", "path": logical,
        "snapshot": deepcopy(tool_pin), "configuration": deepcopy(configuration_pin),
        "helper": deepcopy(helper_pin),
    })
    return data


