def _slicer_snapshot(image, kind, where):
    fields = {"width", "height", "stack_size", "channels", "slices", "frames", "is_hyperstack", "imagej_type", "bit_depth",
        "current_slice_one_based", "title", "encoding", "raw_axes", "raw_hex", "storage_raw_hex", "raw_byte_count",
        "scalar_calibration", "roi", "processor_states", "slice_labels"}
    image = schema.obj(image, where)
    if set(image) != fields:
        schema.fail(where, "actual Java snapshot is missing complete typed/scalar fields")
    for name in ("width", "height", "stack_size"):
        _integer(image[name], where, 1, 4096)
    for name, expected in (("channels", 1), ("frames", 1), ("slices", image["stack_size"]),
        ("is_hyperstack", False), ("imagej_type", {"u8": 0, "u16": 1, "f32": 2}[kind]),
        ("bit_depth", {"u8": 8, "u16": 16, "f32": 32}[kind]), ("raw_axes", "ZYX"),
        ("encoding", {"u8": "UInt8", "u16": "UInt16LE", "f32": "Float32LE"}[kind])):
        _axis_equal(image[name], expected, where, "actual snapshot " + name)
    raw = image["raw_hex"]
    count = image["width"] * image["height"] * image["stack_size"] * {"u8": 1, "u16": 2, "f32": 4}[kind]
    if type(raw) is not str or count > 64 * 1024**2 or len(raw) != 2 * count or not re.fullmatch("[0-9a-f]+", raw):
        schema.fail(where, "requires all canonical primitive typed bytes, never a precomputed digest")
    _axis_equal(image["storage_raw_hex"], raw, where, "primitive storage and typed bits")
    _axis_equal(image["raw_byte_count"], count, where, "captured full byte count")
    payload = bytes.fromhex(raw)
    if kind == "f32" and any(not math.isfinite(value[0]) for value in struct.iter_unpack("<f", payload)):
        schema.fail(where, "nonfinite F32 is outside the captured scalar fixture")
    calibration = schema.obj(image["scalar_calibration"], where)
    cal_fields = {"spacing", "spacing_float64_raw_hex", "origin_pixels", "origin_float64_raw_hex", "unit", "x_unit", "y_unit",
        "z_unit", "time_unit", "frame_interval", "frame_interval_raw_hex", "fps", "loop", "info", "invert_y", "value_unit",
        "density_function", "density_coefficients", "zero_clip", "signed_16bit", "coordinate_functions_at_zero_xyz", "coordinate_y_at_zero_with_height"}
    if set(calibration) != cal_fields:
        schema.fail(where, "actual Java scalar calibration field set differs")
    _axis_equal(calibration["spacing_float64_raw_hex"], _slicer_spacing(calibration["spacing"], where), where, "actual scalar64 transport")
    origins = schema.array(calibration["origin_pixels"], where)
    if len(origins) != 3:
        schema.fail(where, "all observed ImageJ pixel offsets must remain captured")
    for number in origins:
        schema.number(number, where)
    _axis_equal(calibration["origin_float64_raw_hex"], [struct.pack(">d", float(number)).hex() for number in origins], where, "offset bit transport only")
    schema.number(calibration["frame_interval"], where)
    _axis_equal(calibration["frame_interval_raw_hex"], struct.pack(">d", float(calibration["frame_interval"])).hex(), where, "time scalar bit transport only")
    execution.finite_json(image, where)
    return {"shape_tczyxs": [1, 1, image["stack_size"], image["height"], image["width"], 1],
        "encoding": image["encoding"], "byte_count": count, "typed_sha256": hashlib.sha256(payload).hexdigest(),
        "scalar_spacing_float64_hex": calibration["spacing_float64_raw_hex"]}


