def _structure(expected, observed, where):
    if isinstance(expected, dict):
        if not isinstance(observed, dict) or set(expected) != set(observed):
            schema.fail(where, "observed object keys differ from the expected output")
        for key in expected:
            _structure(expected[key], observed[key], where)
    elif isinstance(expected, list):
        if not isinstance(observed, list) or len(expected) != len(observed):
            schema.fail(where, "observed container dimensions differ from the expected output")
        for left, right in zip(expected, observed):
            _structure(left, right, where)
    elif type(expected) in {int, float}:
        schema.number(observed, where)
    elif type(expected) is not type(observed):
        schema.fail(where, "observed scalar type differs from the expected output")


def _compare(expected, observed, comparison, tolerance, where):
    _structure(expected, observed, where)
    if isinstance(expected, dict):
        for key in expected:
            _compare(expected[key], observed[key], comparison, tolerance, where)
    elif isinstance(expected, list):
        for left, right in zip(expected, observed):
            _compare(left, right, comparison, tolerance, where)
    elif type(expected) in {int, float}:
        if tolerance:
            try:
                difference = abs(observed - expected)
                limit = comparison["atol"] + comparison["rtol"] * abs(expected)
                finite = math.isfinite(difference) and math.isfinite(limit)
            except OverflowError:
                finite = False
            if not finite:
                schema.fail(where, "nonfinite or overflowing comparison arithmetic")
            if difference > limit:
                schema.fail(where, "observed numerical output is outside reference-relative tolerance")
        elif expected != observed:
            schema.fail(where, "observed numerical output differs from exact expected value")
    elif tolerance:
        schema.fail(where, "numeric tolerance selector contains a nonnumeric scalar")
    elif not execution.same(expected, observed):
        schema.fail(where, "observed output differs from exact expected value")


