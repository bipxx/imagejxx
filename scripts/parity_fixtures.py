def _slicer_windows_path(value, where):
    schema.text(value, where)
    path = PureWindowsPath(value)
    parts = value.replace("\\", "/").rstrip("/").split("/")
    if not path.is_absolute() or not re.fullmatch("[A-Za-z]:", path.drive) or any(part in {"", ".", ".."} for part in parts):
        schema.fail(where, "captured Windows path must be a literal local absolute path")
    return path


def _slicer_file_url(value, where):
    parsed = urlsplit(value)
    if parsed.scheme != "file" or parsed.netloc or parsed.query or parsed.fragment:
        schema.fail(where, "actual Java CodeSource requires a local file URL")
    try:
        decoded = unquote_to_bytes(parsed.path).decode("utf-8")
    except UnicodeError as error:
        schema.fail(where, f"invalid Java CodeSource UTF-8: {error}")
    return _slicer_windows_path(decoded.removeprefix("/"), where)


