def _source_tree(root, fixture, contract, pins, payloads, result):
    """Inspect literal constants and local imports; never import capture code."""
    where = contract["id"]
    sources = {pin["path"]: pin for pin in pins}
    primary_path = fixture["generator"]["path"]
    module_root = PurePosixPath(primary_path).parent
    primary = sources.get(primary_path)
    complete = True
    if primary is None:
        if any(PurePosixPath(path).name == PurePosixPath(primary_path).name for path in sources):
            schema.fail(where, "capture primary generator source path differs from the fixture generator")
        _capture_gap(result, fixture, contract, "generator_sources", "Primary generator source identity is missing")
        complete = False
    elif any(primary[key] != fixture["generator"][key] for key in ("path", "sha256")):
        schema.fail(where, "capture primary generator differs from the fixture generator")
    trees, constants = {}, {}
    for path, pin in sources.items():
        data = payloads.get(pin["path"])
        if data is None:
            complete = False
            continue
        try:
            tree = ast.parse(data.decode("utf-8-sig"), filename=pin["path"])
        except (SyntaxError, UnicodeError) as error:
            schema.fail(where, f"invalid statically inspected generator source: {error}")
        trees[path] = tree
        literal = {}
        for node in tree.body:
            targets = node.targets if isinstance(node, ast.Assign) else [node.target] if isinstance(node, ast.AnnAssign) else []
            for target in targets:
                if isinstance(target, ast.Name) and node.value is not None:
                    try:
                        literal[target.id] = ast.literal_eval(node.value)
                    except (ValueError, TypeError):
                        pass  # Nonliteral expressions are inspected as syntax only.
        constants[path] = literal

    def unresolved(module, reason):
        nonlocal complete
        _capture_gap(result, fixture, contract, "generator_sources", f"Unresolved capture dependency {module}: {reason}")
        complete = False

    def exists(path):
        return evidence.report_path(root, str(path), where).is_file()

    def declared(path):
        return str(path) in sources

    def require_source(path, module):
        if not declared(path):
            unresolved(module, f"required source identity is missing: {path}")

    def symbols(path):
        tree = trees.get(str(path))
        if tree is None:
            return set()
        found = set()
        for node in ast.walk(tree):
            if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
                found.add(node.name)
            elif isinstance(node, ast.Name) and isinstance(node.ctx, ast.Store):
                found.add(node.id)
            elif isinstance(node, (ast.Import, ast.ImportFrom)):
                found.update(alias.asname or alias.name.split(".")[0] for alias in node.names if alias.name != "*")
        return found

    def resolve(module, base, relative=False):
        """Bind a reviewed module to its actual path, never just a basename."""
        parts = module.split(".") if module else []
        target = base.joinpath(*parts)
        source_file = target.with_suffix(".py") if parts else None
        initializer = target / "__init__.py"
        prefixes = [base.joinpath(*parts[:index]) for index in range(1, len(parts) + 1)]
        shadow_paths = [path for prefix in prefixes for path in (prefix.with_suffix(".py"), prefix / "__init__.py")]
        shadow = any(declared(path) or exists(path) for path in shadow_paths)
        if not relative and parts and parts[0] in sys.stdlib_module_names and not shadow:
            return None, True
        if declared(initializer) or exists(initializer):
            selected = initializer
        elif source_file is not None and (declared(source_file) or exists(source_file)):
            selected = source_file
        else:
            if source_file is not None and any(PurePosixPath(path).name == source_file.name for path in sources):
                schema.fail(where, f"capture helper source path does not match imported module {module}: {source_file}")
            unresolved(module or str(base), "static module origin is not represented by a source pin")
            return None, False
        if not declared(selected) and selected.name != "__init__.py" and any(PurePosixPath(path).name == selected.name for path in sources):
            schema.fail(where, f"capture helper source path does not match imported module {module}: {selected}")
        require_source(selected, module or str(base))
        # Package code executes before its member module. Every initializer is
        # an explicit identity; namespace packages remain unresolved evidence.
        try:
            package_parts = base.relative_to(module_root).parts
        except ValueError:
            unresolved(module, "relative import escapes the frozen module search root")
            return None, False
        for index in range(1, len(package_parts) + 1):
            require_source(module_root.joinpath(*package_parts[:index]) / "__init__.py", module)
        for index in range(1, len(parts)):
            require_source(base.joinpath(*parts[:index]) / "__init__.py", module)
        return selected, False

    dynamic_loaders = {
        "import_module", "spec_from_file_location", "spec_from_loader",
        "module_from_spec", "SourceFileLoader", "SourcelessFileLoader",
        "ExtensionFileLoader", "load_module", "exec_module",
    }
    for path, tree in trees.items():
        loader_aliases = {"__import__"}
        for node in ast.walk(tree):
            if isinstance(node, ast.ImportFrom) and (node.module or "").split(".")[0] == "importlib":
                loader_aliases.update(alias.asname or alias.name for alias in node.names if alias.name in dynamic_loaders)
        for node in ast.walk(tree):
            if isinstance(node, ast.Call) and (
                isinstance(node.func, ast.Name) and node.func.id in loader_aliases
                or isinstance(node.func, ast.Attribute) and node.func.attr in dynamic_loaders
            ):
                label = node.func.id if isinstance(node.func, ast.Name) else node.func.attr
                unresolved(label, "dynamic source loading is not a reviewed static import identity")
            elif isinstance(node, ast.Import):
                for alias in node.names:
                    resolve(alias.name, module_root)
            elif isinstance(node, ast.ImportFrom):
                base = PurePosixPath(path).parent if node.level else module_root
                for _ in range(max(0, node.level - 1)):
                    base = base.parent
                if node.level:
                    try:
                        base.relative_to(module_root)
                    except ValueError:
                        unresolved(node.module or ".", "relative import escapes the frozen module search root")
                        continue
                selected, stdlib = resolve(node.module or "", base, relative=bool(node.level))
                if stdlib or selected is None or selected.name != "__init__.py":
                    continue
                exports = symbols(selected)
                for alias in node.names:
                    if alias.name == "*":
                        unresolved(node.module or str(base), "wildcard package member imports are not reviewed")
                    elif alias.name not in exports:
                        resolve(alias.name, selected.parent, relative=True)
    if contract["format"] != "owned_cases_v1":
        for literal in constants.values():
            for key, value in (("COMMIT", fixture["reference"]["revision"]), ("IMAGEJ_SHA", fixture["reference"]["archive_sha256"])):
                if key in literal and literal[key] != value:
                    schema.fail(where, "capture helper literal reference identity differs")
    primary_constants = constants.get(primary_path, {})
    return complete, primary_constants


def _rank_capture_bytes(root, pin, where, result, kind, **identities):
    """Read only the declared small retained input; never execute capture sources."""
    execution.file_identity(pin, where)
    size = _integer(pin.get("bytes"), where, 1, 1024 * 1024)
    target = evidence.report_path(root, pin["path"], where)
    if not target.exists():
        _gap(result, "unavailable_evidence", "Retained rank capture bytes are unavailable",
             kind=kind, path=pin["path"], **identities)
        return None
    if not target.is_file() or target.stat().st_size != size:
        schema.fail(where, "retained rank capture file size/type differs from its exact bounded pin")
    with target.open("rb") as stream:
        data = stream.read(size + 1)
    if len(data) != size or hashlib.sha256(data).hexdigest() != pin["sha256"]:
        schema.fail(where, "retained rank capture byte identity changed")
    return data


def _rank_capture_digest(value):
    # The owned extractor's original row/observation identities use ASCII JSON.
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(",", ":"),
                                    ensure_ascii=True, allow_nan=False).encode("utf-8")).hexdigest()


def _rank_observed_run(case_id, observation, where):
    """Select captured bytes and metadata only; no filtering or pixel arithmetic."""
    observation = schema.obj(observation, where)
    spec = schema.obj(observation.get("input"), where)
    source = schema.obj(spec.get("fixture"), where)
    before = schema.obj(observation.get("before"), where)
    after = schema.obj(observation.get("after"), where)
    for key in ("shape_tczyx", "position_tcz"):
        _axis_equal(before.get(key), source.get(key), where, "observed rank input " + key)
    requested = schema.array(source.get("planes"), where)
    old = schema.array(before.get("planes"), where)
    new = schema.array(after.get("planes"), where)
    coordinates = lambda planes: [[plane.get(key) for key in ("t", "c", "z")] for plane in planes]
    _axis_equal(coordinates(old), coordinates(requested), where, "observed rank source planes")
    _axis_equal(coordinates(new), coordinates(requested), where, "observed rank output planes")
    planes = []
    for request, first, last in zip(requested, old, new):
        _axis_equal(first.get("bits_hex"), request.get("bits_hex"), where, "consumed rank source bits")
        planes.append({"tcz": [first.get(key) for key in ("t", "c", "z")],
                       "before_hex": first.get("bits_hex"), "after_hex": last.get("bits_hex")})
    return {"id": case_id + "/" + schema.text(spec.get("name"), where), "source_case_id": case_id,
        "source_observation_sha256": _rank_capture_digest(observation), "dtype": source.get("dtype"),
        "shape_tczyx": source.get("shape_tczyx"), "position_tcz": source.get("position_tcz"),
        "roi": source.get("roi"), "dispatch": spec.get("dispatch"), "all_stack": spec.get("all_stack"),
        "method": spec.get("method"), "radius": spec.get("radius"), "planes": planes}


def _rank_validate_capture(root, fixture, contract, corpus, result, projections=None):
    """Verify the exact retained 16-row capture plus its signed-zero supplement.

    This checks existing source/input/observed bytes, not a new Java execution or
    a retrospective process receipt. Original out-of-profile rows stay intact.
    """
    where = contract["id"]
    capture = schema.obj(contract.get("capture"), where)
    roles = {"kind", "generator_sources", *RANK_CAPTURE_PINS}
    missing = roles - capture.keys()
    if missing:
        for role in sorted(missing):
            _capture_gap(result, fixture, contract, role, "Retained rank capture identity role is missing")
        return False
    _rank_keys(capture, roles, where)
    _axis_equal(capture["kind"], "retained_imagej_rank_selection_v1", where, "retained rank capture kind")
    _axis_equal(capture["generator_sources"], [RANK_GENERATOR], where, "owned retained rank extractor source")
    for role, pin in RANK_CAPTURE_PINS.items():
        _axis_equal(capture[role], pin, where, "retained rank " + role)
    identities = {"fixture_id": fixture["id"], "contract_id": where}
    payloads = {role: _rank_capture_bytes(root, pin, where, result, role, **identities)
                for role, pin in RANK_CAPTURE_PINS.items()}
    extractor = _rank_capture_bytes(root, RANK_GENERATOR, where, result, "generator_source", **identities)
    if corpus is None or extractor is None or any(data is None for data in payloads.values()):
        _capture_gap(result, fixture, contract, "capture", "Exact retained rank source/capture inputs are unavailable")
        return False
    _rank_embedded_identity(corpus, fixture, where)
    rows = [execution.strict_json(line, where) for line in payloads["raw_output"].splitlines()]
    ids = [f"K{index:02d}" for index in range(1, 17)]
    if len(rows) != 16 or [schema.obj(row, where).get("id") for row in rows] != ids:
        schema.fail(where, "complete retained rank capture must preserve its sixteen ordered original rows")
    plan = schema.obj(execution.strict_json(payloads["input_plan"], where), where)
    _axis_equal(plan.get("ordered_case_ids"), ids, where, "original rank source plan order")
    _axis_equal([row.get("input_contract") for row in rows], plan.get("cases"), where, "consumed rank source plan")
    counts = (0, 3, 3, 3, 3, 8, 1, 1, 108, 8, 12, 4, 12, 8, 0, 0)
    inventory = corpus["provenance"]["original_case_inventory"]
    selected = []
    for index, (row, count) in enumerate(zip(rows, counts)):
        original_runs = schema.array(schema.obj(row.get("input_contract"), where).get("runs", []), where)
        if len(original_runs) != count:
            schema.fail(where, "original rank 174-run membership changed")
        _axis_equal(_rank_capture_digest(row), inventory[index]["row_sha256"], where, "complete original rank row")
        if index in (*range(1, 11), 13):
            observations = schema.array(row.get("observations"), where)
            _axis_equal([schema.obj(item, where).get("input") for item in observations], original_runs,
                        where, "actual finite rank observations match consumed requests")
            selected.extend(_rank_observed_run(row["id"], item, where) for item in observations)
    if sum(counts) != 174 or len(selected) != 158:
        schema.fail(where, "retained rank original/selected denominators changed")
    footprints = []
    for observation in schema.array(rows[0].get("observations"), where):
        wire = schema.array(schema.obj(observation, where).get("line_radii"), where)
        footprints.append({"id": "K01/" + str(observation.get("radius")), "radius": observation.get("radius"),
            "half_widths": wire[1:-2:2], "point_count": observation.get("point_count"),
            "offsets_xy": observation.get("offsets_xy")})
    _axis_equal(footprints, corpus["kernels"], where, "ten separate captured footprints")
    supplemental_rows = [execution.strict_json(line, where) for line in payloads["supplement_output"].splitlines()]
    if len(supplemental_rows) != 1:
        schema.fail(where, "retained rank signed-zero supplement must contain one original row")
    supplement = schema.obj(supplemental_rows[0], where)
    _axis_equal(supplement.get("contract"), "g042.rank-filter-signed-zero-reference.001", where, "signed-zero contract")
    _axis_equal(supplement.get("id"), "SZ01", where, "signed-zero original case")
    observations = schema.array(supplement.get("observations"), where)
    if len(observations) != 3:
        schema.fail(where, "retained rank signed-zero supplement requires three filtered runs")
    _axis_equal([schema.obj(item, where).get("input") for item in observations], supplement.get("inputs"),
                where, "actual signed-zero requests")
    selected.extend(_rank_observed_run("SZ01", item, where) for item in observations)
    _axis_equal(selected, corpus["runs"], where, "complete 158+3 retained filtered observations")
    verified = schema.obj(execution.strict_json(payloads["verified_inputs"], where), where)
    _axis_equal(verified.get("reference"), corpus["reference"], where, "retained verified rank reference")
    _axis_equal(verified.get("known_source_members"), corpus["provenance"]["source_members"], where, "retained original source identities")
    _axis_equal(verified.get("rank_source_members"), corpus["provenance"]["rank_source_members"], where, "retained rank source identities")
    schema.obj(execution.strict_json(payloads["execution_inputs"], where), where)
    if projections is not None:
        _axis_equal(projections, _rank_project(corpus, where), where, "complete frozen rank projections")
    return True


def _validate_capture(root, fixture, contract, projections, corpus, result):
    where = contract["id"]
    capture = contract.get("capture")
    if capture is None:
        _capture_gap(result, fixture, contract, "capture", "Frozen capture identity is missing")
        return False
    schema.obj(capture, where)
    if contract["format"] == RANK_FORMAT:
        return _rank_validate_capture(root, fixture, contract, corpus, result, projections)
    if contract["format"] == ORIENTATION_FORMAT:
        return _orientation_validate_capture(root, fixture, contract, corpus, result, projections)
    if contract["format"] == SLICER_FORMAT:
        return _slicer_validate_capture(root, fixture, contract, corpus, result, projections)
    roles = {"receipt", "raw_output", "generator_sources", "reference_archive", "reference_members", "driver", "runtime"}
    supported = contract["format"] in FORMATS
    complete = roles <= capture.keys() and supported
    if contract["format"] in {AXIS_FORMAT, RANGE_FORMAT}:
        complete = _axis_validate_capture(root, fixture, contract, corpus, result) and complete
    for role in sorted(roles - capture.keys()):
        _capture_gap(result, fixture, contract, role, "Capture identity role is missing")
    identities = {"fixture_id": fixture["id"], "contract_id": where}
    payloads = {}
    for role in ("receipt", "raw_output", "reference_archive"):
        if role in capture:
            payloads[role] = _bytes(root, capture[role], where, result, role, **identities)
            if payloads[role] is None:
                complete = False
    source_data, constants = {}, {}
    if "generator_sources" in capture:
        pins = _pins(capture["generator_sources"], where)
        for pin in pins:
            source_data[pin["path"]] = _bytes(root, pin, where, result, "generator_source", **identities)
            if source_data[pin["path"]] is None:
                complete = False
        source_complete, constants = _source_tree(root, fixture, contract, pins, source_data, result)
        complete = complete and source_complete
    if "reference_archive" in capture and capture["reference_archive"]["sha256"] != fixture["reference"]["archive_sha256"]:
        schema.fail(where, "capture reference archive differs from the fixture reference")
    if "reference_members" in capture:
        members = _pins(capture["reference_members"], where)
        expected = {row["path"]: row["sha256"] for row in fixture["reference"]["source_members"]}
        if {row["path"]: row["sha256"] for row in members} != expected:
            schema.fail(where, "capture reference member set/hashes differ from the complete fixture reference")
        data = payloads.get("reference_archive")
        if data is not None:
            try:
                with zipfile.ZipFile(BytesIO(data)) as archive:
                    for member in members:
                        matches = [entry for entry in archive.infolist() if entry.filename == member["path"]]
                        if len(matches) != 1 or matches[0].is_dir():
                            schema.fail(where, "reference archive member is absent or ambiguous")
                        if hashlib.sha256(archive.read(matches[0])).hexdigest() != member["sha256"]:
                            schema.fail(where, "reference archive member bytes changed")
            except (zipfile.BadZipFile, RuntimeError, OSError) as error:
                schema.fail(where, f"invalid reference archive: {error}")
    owned = contract["format"] == "owned_cases_v1"
    java_adapter = supported and not owned
    if "driver" in capture:
        driver = capture["driver"]
        if owned:
            if driver is not None:
                schema.fail(where, "owned synthetic capture requires a null driver")
        elif not supported and driver is None:
            pass  # An unknown adapter is a gap, not an implicit Java contract.
        else:
            schema.obj(driver, where)
            schema.sha(driver.get("text_sha256"), where)
            data = _bytes(root, driver.get("artifact"), where, result, "driver_artifact", **identities)
            if data is None:
                complete = False
            driver_text = (_axis_driver_text(source_data.get(fixture["generator"]["path"]),
                                             driver, fixture, where, data, contract["format"])
                           if contract["format"] in {AXIS_FORMAT, RANGE_FORMAT} else constants.get("DRIVER"))
            if driver_text is None:
                _capture_gap(result, fixture, contract, "driver", "Pinned primary generator DRIVER literal is unavailable")
                complete = False
            elif not isinstance(driver_text, str):
                schema.fail(where, "embedded DRIVER must be a literal string")
            else:
                text_sha = hashlib.sha256(driver_text.encode("utf-8")).hexdigest()
                if driver["text_sha256"] != text_sha or "driver_sha256" in fixture["generator"] and fixture["generator"]["driver_sha256"] != text_sha:
                    schema.fail(where, "embedded driver text fingerprint changed")
                if data is not None:
                    try:
                        emitted = data.decode("utf-8").replace("\r\n", "\n")
                    except UnicodeError as error:
                        schema.fail(where, f"driver artifact is not UTF-8: {error}")
                    if emitted != driver_text:
                        schema.fail(where, "emitted driver text differs from the pinned DRIVER literal")
    if "runtime" in capture:
        runtime = schema.obj(capture["runtime"], where)
        kind = schema.text(runtime.get("kind"), where)
        if owned and kind != "owned_synthetic" or java_adapter and kind != "java":
            schema.fail(where, "capture runtime kind differs from the allowlisted adapter")
        schema.text(runtime.get("version"), where)
        if corpus is not None and "runtime_version" in corpus and runtime["version"] != corpus["runtime_version"]:
            schema.fail(where, "capture runtime version differs from the corpus")
        if kind == "owned_synthetic":
            runtime_roles = ("executables", "sources")
        elif kind == "java":
            runtime_roles = ("executables", "classpath", "classes", "resources")
        else:
            _gap(result, "unsupported_methods", "Capture runtime identity schema is not implemented", runtime_kind=kind, **identities)
            complete = False
            runtime_roles = tuple(role for role in ("executables", "sources", "classpath", "classes", "resources") if role in runtime)
        for role in runtime_roles:
            for pin in _pins(runtime.get(role), where, nonempty=role != "resources"):
                if _bytes(root, pin, where, result, "runtime_" + role, **identities) is None:
                    complete = False
    receipt_data = payloads.get("receipt")
    if receipt_data is not None:
        receipt = schema.obj(execution.strict_json(receipt_data, where), where)
        schema.version(receipt.get("schema_version"), where)
        if receipt.get("fixture_sha256") != fixture["sha256"] or type(receipt.get("case_count")) is not int or receipt["case_count"] != fixture["case_count"]:
            schema.fail(where, "capture receipt fixture identity/count differs")
        for role in ("exit_code", "reference_errors"):
            if type(receipt.get(role)) is not int or receipt[role] != 0:
                schema.fail(where, "capture receipt records failed execution or reference errors")
        if "receipt" in receipt:
            schema.fail(where, "capture receipt must not include its own pin")
        for role in roles - {"receipt"}:
            if role in capture and (role not in receipt or not execution.same(receipt[role], capture[role])):
                schema.fail(where, "capture receipt identity differs from the frozen capture declaration")
    raw_data = payloads.get("raw_output")
    if raw_data is not None:
        try:
            lines = raw_data.decode("utf-8").split("\n")
            if lines[-1] == "":
                lines.pop()
            lines = [line.removesuffix("\r") for line in lines]
        except UnicodeError as error:
            schema.fail(where, f"raw captured output is not UTF-8 JSONL: {error}")
        if not lines or any(not line.strip() for line in lines):
            schema.fail(where, "raw captured output requires nonempty ordered JSONL records")
        cases = [execution.strict_json(line.encode("utf-8"), where) for line in lines]
        if len(cases) != fixture["case_count"]:
            schema.fail(where, "raw captured output count differs from the complete corpus")
        if contract["format"] in FORMATS:
            raw_projections = project_cases(contract["format"], {"schema_version": 1, "cases": cases})
            for case, raw in zip(contract["case_set"], raw_projections):
                if case["input_sha256"] != _digest(raw["input"]) or case["expected_sha256"] != _digest(raw["expected"]):
                    schema.fail(where, "raw captured input/expected projections differ from the frozen corpus")
            if projections is not None and not execution.same(projections, raw_projections):
                schema.fail(where, "raw capture projections differ from the complete pinned content")
    if not complete:
        _capture_gap(result, fixture, contract, "capture", "Capture provenance is incomplete or unavailable")
    return complete


def _axis_driver_text(primary_data, driver, fixture, where, artifact_data, format_name=AXIS_FORMAT):
    """Allow exactly the reviewed same-directory external Path, never execute it."""
    _axis_equal(driver.get("source_mode"), "same_directory_python_path_v1", where, "driver source mode")
    driver_pin, generator = (RANGE_DRIVER, RANGE_GENERATOR) if format_name == RANGE_FORMAT else (AXIS_DRIVER, AXIS_GENERATOR)
    _axis_equal(driver.get("artifact"), driver_pin, where, "external Java driver artifact")
    _axis_equal(driver.get("text_sha256"), driver_pin["sha256"], where, "external Java driver text pin")
    _axis_equal(fixture["generator"]["path"], generator["path"], where, "external-driver generator path")
    if primary_data is None:
        return None
    tree = ast.parse(primary_data.decode("utf-8-sig"))
    assignments = {}
    for node in tree.body:
        if isinstance(node, ast.Assign):
            for target in node.targets:
                if isinstance(target, ast.Name) and target.id in {"HERE", "DRIVER"}:
                    if target.id in assignments:
                        schema.fail(where, "axis-plane driver path binding is reassigned")
                    assignments[target.id] = ast.dump(node.value, include_attributes=False)
    expected = {
        "HERE": "Path(__file__).resolve().parent", "DRIVER": 'HERE / "' + PurePosixPath(driver_pin["path"]).name + '"',
    }
    for key, expression in expected.items():
        if assignments.get(key) != ast.dump(ast.parse(expression, mode="eval").body,
                                            include_attributes=False):
            schema.fail(where, "axis-plane external driver requires the exact static same-directory Path binding")
    # Source hash and artifact bytes are verified separately by the existing
    # generator/artifact roles; only the reviewed artifact supplies the text.
    if artifact_data is None:
        return None
    try:
        text = artifact_data.decode("utf-8")
    except UnicodeError as error:
        schema.fail(where, f"axis-plane external Java source is not UTF-8: {error}")
    if hashlib.sha256(artifact_data).hexdigest() != driver_pin["sha256"]:
        schema.fail(where, "axis-plane external Java source bytes changed")
    return text


