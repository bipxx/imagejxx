def _validate_contracts(manifest, fixtures, requirements, contents, result):
    contracts = {}
    fixture_ids = set()
    for contract in schema.rows(manifest.get("fixture_contracts", []), "fixture contracts"):
        where = contract["id"]
        execution.finite_json(contract, where)
        fixture_id = schema.identity(contract.get("fixture_id"), where)
        if fixture_id not in fixtures or fixture_id in fixture_ids:
            schema.fail(where, "unknown fixture or duplicate fixture contract")
        fixture_ids.add(fixture_id)
        fixture = fixtures[fixture_id]
        if not execution.same(contract.get("fixture_snapshot"), fixture_snapshot(fixture, requirements)):
            schema.fail(where, "frozen fixture snapshot differs from the current fixture/children")
        format_name = schema.text(contract.get("format"), where)
        if format_name not in FORMATS:
            _gap(result, "unsupported_methods", "Fixture adapter is not implemented", fixture_id=fixture_id, contract_id=where, format=format_name)
        legacy = _legacy_format(fixture)
        if legacy is not None and format_name != legacy:
            schema.fail(where, "contract adapter differs from the reviewed legacy generator")
        cases = schema.array(contract.get("case_set"), where)
        if len(cases) != fixture["case_count"]:
            schema.fail(where, "case set must enumerate the complete corpus")
        if format_name == ORIENTATION_FORMAT and len(cases) != 96:
            schema.fail(where, "orientation contract requires exactly96 original cases and672 selectors")
        if format_name == SLICER_FORMAT and len(cases) != 240:
            schema.fail(where, "Slicer contract requires exactly240 original cases and1680 selectors")
        case_ids, required = set(), set()
        projections = contents.get(fixture_id)
        for index, case in enumerate(cases):
            schema.obj(case, where)
            case_id = schema.identity(case.get("case_id"), where)
            if case_id in case_ids:
                schema.fail(where, "duplicate case ID")
            case_ids.add(case_id)
            if type(case.get("locator")) is not int or case["locator"] != index:
                schema.fail(where, "case locators must follow complete zero-based corpus order")
            for key in ("input_sha256", "expected_sha256"):
                schema.sha(case.get(key), where)
            paths = _selectors(case.get("required_output_paths"), where)
            if format_name == AXIS_FORMAT:
                _axis_equal(case_id, AXIS_CASE_IDS[index], where, "ordered contract case ID")
                _axis_equal(paths, list(AXIS_OUTPUT_PATHS), where, "seven exact scientific selectors")
            if format_name == RANGE_FORMAT:
                _axis_equal(case_id, RANGE_CASE_IDS[index], where, "ordered range contract case ID")
                _axis_equal(paths, list(RANGE_OUTPUT_PATHS), where, "seven exact range scientific selectors")
            if format_name == ORIENTATION_FORMAT:
                _axis_equal(case_id, ORIENTATION_CASE_IDS[index], where, "ordered orientation contract case ID")
                _axis_equal(paths, list(ORIENTATION_OUTPUT_PATHS), where, "seven exact orientation scientific selectors")
            if format_name == SLICER_FORMAT:
                _axis_equal(case_id, SLICER_CASE_IDS[index], where, "ordered Slicer contract case ID")
                _axis_equal(paths, list(SLICER_OUTPUT_PATHS), where, "seven exact Slicer scientific selectors")
            if projections is not None:
                projection = projections[index]
                if case["input_sha256"] != _digest(projection["input"]) or case["expected_sha256"] != _digest(projection["expected"]):
                    schema.fail(where, "complete input/expected projection fingerprint differs")
                for path in paths:
                    _pointer(projection["expected"], path, where)
                    if format_name == "imagej_roi_style_v1" and path == "/width" and projection["input"]["operation"] != "width":
                        schema.fail(where, "only reviewed width cases establish width comparisons")
            required.update((case_id, path) for path in paths)
        if not required:
            schema.fail(where, "fixture contract requires a nonempty assertion denominator")
        scopes = schema.array(contract.get("requirement_scopes"), where)
        children, union = set(), set()
        for scope in scopes:
            schema.obj(scope, where)
            child_id = schema.identity(scope.get("requirement_id"), where)
            if child_id not in fixture["requirement_ids"] or child_id in children:
                schema.fail(where, "unknown or duplicate linked child scope")
            children.add(child_id)
            if not execution.same(scope.get("snapshot"), execution.frozen_snapshot(requirements[child_id])):
                schema.fail(where, "frozen child scope snapshot differs")
            schema.texts(scope.get("exclusions"), where)
            pairs = set()
            for selector in schema.array(scope.get("required"), where):
                schema.obj(selector, where)
                case_id = schema.identity(selector.get("case_id"), where)
                path = schema.text(selector.get("path"), where, empty=True)
                pair = case_id, path
                if pair not in required or pair in pairs:
                    schema.fail(where, "unknown or duplicate child output assertion")
                pairs.add(pair)
                if projections is not None and format_name == "imagej_roi_style_v1" and child_id.endswith(".stroke_width"):
                    index = next(i for i, case in enumerate(cases) if case["case_id"] == case_id)
                    if projections[index]["input"]["operation"] != "width" or path != "/width":
                        schema.fail(where, "stroke-width child coverage is restricted to reviewed width cases")
            if not pairs:
                schema.fail(where, "linked child scope requires explicit assertions")
            union.update(pairs)
        if children != set(fixture["requirement_ids"]) or union != required:
            schema.fail(where, "linked scope union differs from the frozen required assertion set")
        comparison = schema.obj(contract.get("comparison"), where)
        for key, value in fixture["comparison"].items():
            if not execution.same(comparison.get(key), value):
                schema.fail(where, "contract comparison differs from the fixture")
        if format_name in {SLICER_FORMAT, RANK_FORMAT} and comparison.get("method") != "exact":
            schema.fail(where, "Slicer/rank typed bytes/scalar bits require exact comparison")
        paths = _selectors(comparison.get("numeric_paths"), where)
        schema.text(comparison.get("units"), where)
        schema.text(comparison.get("rationale"), where)
        if comparison.get("nonfinite") != "reject":
            schema.fail(where, "comparison must reject nonfinite values")
        method = comparison["method"]
        if method == "exact" and paths:
            schema.fail(where, "exact comparison requires empty numeric_paths")
        if method == "float_tolerance" and not paths:
            schema.fail(where, "float tolerance requires reviewed numeric_paths")
        if not set(paths) <= {path for _, path in required}:
            schema.fail(where, "tolerance selectors must be declared required outputs")
        if projections is not None and method == "float_tolerance":
            for case in cases:
                for path in case["required_output_paths"]:
                    if path in paths:
                        _numeric_json(_pointer(projections[case["locator"]]["expected"], path, where), where)
        if method not in {"exact", "float_tolerance"}:
            _gap(result, "unsupported_methods", "Comparison method is not implemented", fixture_id=fixture_id, contract_id=where, method=method)
        schema.sha(contract.get("sha256"), where)
        if contract["sha256"] != contract_fingerprint(contract):
            schema.fail(where, "frozen fixture contract fingerprint changed")
        contracts[where] = contract
        result["contracts_validated"] += 1
        result["required_case_assertions"] += len(required)
    for fixture_id in fixtures.keys() - fixture_ids:
        _gap(result, "missing_contracts", "Frozen fixture contract is missing", fixture_id=fixture_id)
    return contracts


def validate_fixtures(root, documents, inventory=None, *, require_evidence=False, require_complete=False):
    """Return explicit content/proof gaps, without modifying any input or file."""
    evidence.validate_evidence(root, documents, inventory)
    manifest = documents.get("fixtures.json", {})
    fixtures = {row["id"]: row for row in manifest.get("fixtures", [])}
    result = {
        "fixtures_declared": len(fixtures), "fixtures_required": len(fixtures),
        "content_files_verified": 0, "contracts_required": len(fixtures),
        "contracts_validated": 0, "required_case_assertions": 0,
        "verified_case_assertions": 0, **{key: [] for key in GAP_KEYS},
    }
    if EXTENSION & manifest.keys():
        if not EXTENSION <= manifest.keys():
            schema.fail("fixtures.json", "incomplete fixture evidence extension")
        schema.version(manifest["fixture_evidence_schema_version"], "fixture evidence")
    requirements = {row["id"]: row for row in documents["commands.json"].get("requirements", [])}
    if manifest.get("enumeration_status") != "frozen" or not fixtures:
        _gap(result, "enumeration_gaps", "Fixture enumeration must be frozen and nonempty", kind="fixtures")
    contents, corpora = {}, {}
    declared_formats = {
        row.get("fixture_id"): row.get("format")
        for row in schema.rows(manifest.get("fixture_contracts", []), "fixture contracts")
    }
    for fixture_id, fixture in fixtures.items():
        data = _bytes(root, fixture, fixture_id, result, "fixture", fixture_id=fixture_id)
        _bytes(root, fixture["generator"], fixture_id, result, "generator", fixture_id=fixture_id)
        format_name = declared_formats.get(fixture_id, _legacy_format(fixture))
        if format_name not in FORMATS:
            _gap(result, "unsupported_methods", "Fixture adapter is not implemented", fixture_id=fixture_id, format=format_name)
        if data is not None:
            corpus = execution.strict_json(data, fixture_id)
            schema.obj(corpus, fixture_id)
            case_key = "runs" if format_name == RANK_FORMAT else "cases"
            if len(schema.array(corpus.get(case_key), fixture_id)) != fixture["case_count"]:
                schema.fail(fixture_id, "actual corpus count differs from the declared fixture")
            corpora[fixture_id] = corpus
            if format_name in FORMATS:
                _embedded_identity(corpus, fixture, format_name, fixture_id)
                contents[fixture_id] = project_cases(format_name, corpus)
                result["content_files_verified"] += 1
    contracts = _validate_contracts(manifest, fixtures, requirements, contents, result)
    _validate_evidence_layer(root, documents, inventory, fixtures, contracts, contents, corpora, result, require_evidence)
    if require_complete and any(result[key] for key in GAP_KEYS):
        schema.fail("fixture evidence", "complete fixture evidence required: " + ", ".join(f"{key}={len(result[key])}" for key in GAP_KEYS if result[key]))
    return result


