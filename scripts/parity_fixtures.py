def _axis_source_bytes(dtype):
    result = bytearray()
    for z in range(9):
        for y in range(17):
            for x in range(32):
                if dtype == "u8":
                    result.append((37 * x + 61 * y + 13 * x * y + 43 * z) % 251)
                elif dtype == "u16":
                    result.extend(struct.pack("<H", 6000 * z + 32 * y + x))
                elif dtype == "f32":
                    result.extend(struct.pack("<f", 10000 * z + 100 * y + x + 0.25))
                else:
                    result.extend(((17 * x + 31 * y + 47 * z) % 256,
                                   (71 * x + 11 * y + 29 * z) % 256,
                                   (13 * x + 61 * y + 23 * z) % 256))
    return bytes(result)


def _axis_hex(value, count, item_bytes, dtype, where):
    schema.text(value, where)
    if len(value) != count * item_bytes * 2 or re.fullmatch(r"[0-9a-f]+", value) is None:
        schema.fail(where, "axis-plane typed bytes require exact lowercase hex length")
    raw = bytes.fromhex(value)
    if dtype == "f32" and any(not math.isfinite(value[0]) for value in struct.iter_unpack("<f", raw)):
        schema.fail(where, "axis-plane Float32 reference bytes must be finite")
    return raw


def _axis_snapshot(value, dtype, width, height, depth, spacing, origins, roi, title, where):
    value = schema.obj(value, where)
    encoding, imagej_type, bit_depth, item_bytes = {
        "u8": ("UInt8", 0, 8, 1), "u16": ("UInt16_le", 1, 16, 2),
        "f32": ("Float32_le", 2, 32, 4), "rgb": ("RGB8_interleaved", 4, 24, 3),
    }[dtype]
    required = {"width", "height", "stack_size", "channels", "slices", "frames",
                "is_hyperstack", "imagej_type", "bit_depth", "current_slice_one_based",
                "title", "encoding", "raw_hex", "storage_raw_hex", "calibration", "roi"}
    if not required <= value.keys():
        schema.fail(where, "axis-plane snapshot lacks complete captured annotations")
    for key, expected in (("width", width), ("height", height), ("stack_size", depth),
                          ("channels", 1), ("slices", depth), ("frames", 1),
                          ("imagej_type", imagej_type), ("bit_depth", bit_depth),
                          ("current_slice_one_based", 1)):
        _integer(value.get(key), where, 0)
        _axis_equal(value[key], expected, where, key)
    _boolean(value.get("is_hyperstack"), where)
    _axis_equal(value["is_hyperstack"], False, where, "hyperstack flag")
    _axis_equal(value.get("encoding"), encoding, where, "sample encoding")
    _axis_equal(value.get("title"), title, where, "captured title")
    _axis_equal(value.get("roi"), roi, where, "captured ROI")
    count = width * height * depth
    raw = _axis_hex(value.get("raw_hex"), count, item_bytes, dtype, where)
    storage = _axis_hex(value.get("storage_raw_hex"), count,
                        4 if dtype == "rgb" else item_bytes, dtype, where)
    if dtype == "rgb":
        # ColorProcessor stores B,G,R,unused int32 bytes; alpha is reference-only.
        if any(storage[i:i + 3] != raw[i // 4 * 3:i // 4 * 3 + 3][::-1]
               for i in range(0, len(storage), 4)):
            schema.fail(where, "axis-plane RGB int32 storage disagrees with interleaved samples")
    elif storage != raw:
        schema.fail(where, "axis-plane scalar storage differs from typed samples")
    calibration = schema.obj(value.get("calibration"), where)
    for key in ("spacing", "origin_pixels", "coordinate_functions_at_zero_xyz"):
        values = schema.array(calibration.get(key), where)
        if len(values) != 3:
            schema.fail(where, "axis-plane calibration requires three finite values")
        for item in values:
            schema.number(item, where)
        if key == "spacing" and any(item <= 0 for item in values):
            schema.fail(where, "axis-plane scalar spacing must be positive")
    _axis_equal(calibration["spacing"], spacing, where, "scalar spacing")
    _axis_equal(calibration["origin_pixels"], origins, where, "copied ImageJ pixel origins")
    coordinates = [0.0 if origin == 0 else -origin * scale
                   for origin, scale in zip(origins, spacing)]
    _axis_equal(calibration["coordinate_functions_at_zero_xyz"], coordinates, where,
                "ImageJ coordinate annotations")
    for key, expected in (("unit", "µm"), ("y_unit", "µm"), ("z_unit", "µm"),
                          ("time_unit", "sec"), ("frame_interval", 0.0)):
        _axis_equal(calibration.get(key), expected, where, key)
    return raw


def _axis_plane(case, where):
    if "reference_annotations" in case:
        schema.fail(where, "axis-plane case uses the reserved annotation projection field")
    schema.version(case.get("schema_version"), where)
    dtype, plane = case.get("dtype"), case.get("plane")
    schema.choice(dtype, {"u8", "u16", "f32", "rgb"}, where)
    schema.choice(plane, {"xy", "xz", "yz"}, where)
    position = {"u8": "lower", "u16": "interior", "f32": "upper", "rgb": "interior"}[dtype]
    _axis_equal(case.get("case_id"), f"{dtype}.{plane}.{position}", where, "case ID")
    coordinate = _integer(case.get("coordinate_zero_based"), where, 0,
                          {"xy": 8, "xz": 16, "yz": 31}[plane])
    expected_coordinate = 0 if dtype == "u8" else (
        {"xy": 8, "xz": 16, "yz": 31}[plane] if dtype == "f32" else
        {"xy": 4, "xz": 5, "yz": 7}[plane])
    _axis_equal(coordinate, expected_coordinate, where, "fixed coordinate")
    _axis_equal(case.get("method"), "ImageStack processor duplicate" if plane == "xy" else
                "Slicer.reslice(ImagePlus)", where, "actual reference method")
    _boolean(case.get("controlled_initializer_preference"), where)
    _axis_equal(case["controlled_initializer_preference"], False, where, "initializer preference")
    spacing = [1.0, 1.0, 1.0] if dtype in {"u8", "u16"} else [0.4, 1.2, 3.0]
    origins = [0.0, 0.0, 0.0] if dtype in {"u8", "u16"} else [10.0, -5.0, 2.0]
    defaults = {"startAt": "Top", "flip": False, "rotate": False, "nointerpolate": False,
                "sliceCount": 1, "inputZSpacing": 1.0, "outputZSpacing": 1.0,
                "outputSlices": 1, "rgb": False, "notFloat": False}
    configured = {**defaults, "startAt": "Top" if plane == "xz" else "Left",
                  "nointerpolate": True, "inputZSpacing": spacing[2],
                  "rgb": dtype == "rgb", "notFloat": dtype in {"u8", "u16"}}
    for key, expected in (("defaults", defaults), ("configured", configured),
                          ("completed", {**configured, "inputZSpacing": 1.0})):
        _axis_equal(case.get(key), None if plane == "xy" else expected, where,
                    "recorded " + key + " options")
    roi = None if plane == "xy" else {"type": 0, "bounds_xywh":
        [0, coordinate, 32, 1] if plane == "xz" else [coordinate, 0, 1, 17]}
    source = _axis_snapshot(case.get("source_before"), dtype, 32, 17, 9, spacing, origins,
                            roi, "Axis source " + dtype, where)
    after = _axis_snapshot(case.get("source_after"), dtype, 32, 17, 9, spacing, origins,
                           roi, "Axis source " + dtype, where)
    if source != _axis_source_bytes(dtype) or source != after:
        schema.fail(where, "axis-plane source construction/preservation differs from literal typed inputs")
    _axis_equal(case["source_before"], case["source_after"], where, "complete source preservation")
    width, height = {"xy": (32, 17), "xz": (32, 9), "yz": (17, 9)}[plane]
    order = {"xy": (0, 1, 2), "xz": (0, 2, 1), "yz": (1, 2, 0)}[plane]
    output_spacing = [spacing[index] for index in order]
    output = _axis_snapshot(case.get("output"), dtype, width, height, 1,
                            output_spacing, origins, None,
                            "XY plane of Axis" if plane == "xy" else "Reslice of Axis", where)
    item_bytes = {"u8": 1, "u16": 2, "f32": 4, "rgb": 3}[dtype]
    indices = (range(coordinate * 17 * 32, (coordinate + 1) * 17 * 32) if plane == "xy" else
               (z * 17 * 32 + coordinate * 32 + x for z in range(9) for x in range(32))
               if plane == "xz" else
               (z * 17 * 32 + y * 32 + coordinate for z in range(9) for y in range(17)))
    sampled = b"".join(source[index * item_bytes:(index + 1) * item_bytes] for index in indices)
    if output != sampled:
        schema.fail(where, "axis-plane output differs from the recorded integer-axis source samples")
    for key, expected in (
        ("setup_scope", "Driver reflection, not observed dialog input"),
        ("calibration_scope", "Scalar ImageJ metadata; origin pixels copied without plane rebase; no3x3 direction claim"),
        ("rgb_storage_scope", "RGB comparison uses R/G/B bytes; storage_raw_hex separately retains ColorProcessor int32 bits"),
        ("ui_executed", False),
    ):
        _axis_equal(case.get(key), expected, where, key)
    source_projection = {key: value for key, value in case.items()
                         if key not in {"source_before", "source_after", "output"}}
    source_projection["reference_annotations"] = {
        "input_contract": AXIS_INPUT_CONTRACT,
        **{role: {key: value for key, value in case[role].items() if key != "raw_hex"}
           for role in ("source_before", "source_after", "output")},
    }
    expected = {
        "source_before": {"raw_hex": case["source_before"]["raw_hex"]},
        "source_after": {"raw_hex": case["source_after"]["raw_hex"]},
        "output": {"shape": [1, 1, 1, height, width, 3 if dtype == "rgb" else 1],
                   "pixel_type": {"u8": "UInt8", "u16": "UInt16", "f32": "Float32", "rgb": "UInt8"}[dtype],
                   "S": 3 if dtype == "rgb" else 1, "raw_hex": case["output"]["raw_hex"],
                   "spacing": output_spacing},
    }
    return source_projection, expected


