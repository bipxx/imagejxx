"""Transcribe scalar rays from immutable ImageJ observations; never run target code."""
import argparse
import gzip
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CORPUS = ROOT / 'docs/parity/reviews/G034-imagej-z-projection-reference001/observations.jsonl.gz'
TARGET = ROOT / 'tests/native/imagej_projection_numeric_reference.inc'
SHA256 = 'a22ae856cac15d0f956f935dbe371136da455e428907590b3040d7c7996f7073'


def render():
    raw = CORPUS.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SHA256:
        raise ValueError('Pinned ImageJ projection corpus changed')
    methods = dict(avg='Mean', max='Maximum', min='Minimum', sum='Sum',
                   sd='StdDev', median='Median')
    kinds = dict(u8='UInt8', u16='UInt16', f32='Float32')
    lines = ['// Generated by scripts/generate_projection_numeric_fixture.py.',
             '// Corpus SHA256: ' + SHA256,
             '// Expected bits transcribed from Java output, not calculated in Python.']
    cases = 0
    for row in map(json.loads, gzip.decompress(raw).splitlines()):
        if not row['case_id'].startswith('scalar.') or row['kind'] not in kinds:
            continue
        before, output = row['before'], row['output_api']
        size = before['bit_depth'] // 8
        planes = [[int.from_bytes(b[i:i+size], 'little')
                   for i in range(0, len(b), size)]
                  for b in [bytes.fromhex(p['raw_le_hex']) for p in before['planes']]]
        out_size = output['bit_depth'] // 8
        b = bytes.fromhex(output['planes'][0]['raw_le_hex'])
        expected = [int.from_bytes(b[i:i+out_size], 'little')
                    for i in range(0, len(b), out_size)]
        first, last = row['bounds_one_based']
        signed = before['calibration']['density_function'] == 0
        for pixel, bits in enumerate(expected):
            ray = [p[pixel] for p in planes[first-1:last]]
            assert 0 < len(ray) <= 5
            codes = ', '.join(f'0x{x:08x}U' for x in ray)
            output_type = {8:'UInt8', 16:'UInt16', 32:'Float32'}[output['bit_depth']]
            lines.append('{"%s/p%d", T::%s, M::%s, %s, %d, {%s}, T::%s, 0x%08xU},' %
                         (row['case_id'], pixel, kinds[row['kind']], methods[row['method']],
                          str(signed).lower(), len(ray), codes, output_type, bits))
        cases += 1
    assert cases == 84, cases
    return ('\n'.join(lines) + '\n').encode('ascii')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = render()
    if args.check:
        if TARGET.read_bytes() != expected:
            raise SystemExit('Projection fixture differs from pinned corpus transcription')
    else:
        TARGET.write_bytes(expected)
