"""Typed command replay into explicitly chosen working owners.

The two-pixel sigma1 oracle is the fixed UInt8 [0,255] -> [77,178] fixture;
expected outputs are never generated by a native Gaussian call. These are
workflow integration proofs, separate from the pinned upstream numerical corpus.
"""

from copy import deepcopy
import importlib
import json
import os

import imagejxx as ij
import numpy as np
import pytest

from imagejxx.ui import workflows
from imagejxx.ui.model import Calibration, Document, NamedROI, Selection


def raw_record(*, sigma=1, scaled_units=False):
    original = ij.Document(ij.Dataset(np.array([[0, 255]], np.uint8), axes="YX"))
    return ij.resolve_gaussian_command(
        original.snapshot(),
        options=ij.GaussianBlurCommandOptions(sigma, scaled_units),
    ).record()


def source_state(document):
    return {
        "shape": document.data.shape,
        "dtype": document.data.dtype,
        "pixels": document.data.tobytes(),
        "metadata": deepcopy(document.metadata()),
        "revision": document.revision,
        "dirty": document.dirty,
        "can_undo": document.can_undo,
        "can_redo": document.can_redo,
    }


def assert_source_unchanged(document, before):
    assert source_state(document) == before


def test_h3_w01_raw_record_roundtrip_uses_unchanged_version1_envelope():
    record = raw_record()
    steps = [record]
    before = deepcopy(steps)
    assert workflows.validate_steps(steps) is steps
    assert ij.validate_gaussian_command_record(record) is None
    text = workflows.dumps(steps)
    envelope = json.loads(text)
    assert set(envelope) == {"format", "version", "steps"}
    assert envelope["format"] == "imagejxx-workflow"
    assert type(envelope["version"]) is int and envelope["version"] == 1
    assert envelope["steps"] == before
    assert workflows.loads(text) == before and steps == before


@pytest.mark.parametrize("rebind_request", [None, True, {}, "current_plane", 0],
                         ids=["missing", "boolean", "json-object", "text", "integer"])
def test_h3_w02_typed_working_copy_requires_actual_explicit_target_request(rebind_request):
    document = Document(np.array([[0, 255]], np.uint8))
    steps = [raw_record()]
    before, frozen = source_state(document), deepcopy(steps)
    with pytest.raises(TypeError, match="explicit TargetRequest"):
        workflows.run(document, steps, gaussian_rebind=rebind_request)
    assert_source_unchanged(document, before)
    assert steps == frozen


@pytest.mark.parametrize("destination", [ij.OutputDestination.IN_PLACE,
                                        ij.OutputDestination.NEW_DOCUMENT],
                         ids=["in-place-scratch", "new-document-scratch"])
def test_h3_w03_cross_document_rebind_returns_exact_proposal_without_source_edit(destination):
    document = Document(np.array([[0, 255]], np.uint8), "Destination")
    steps = [raw_record()]
    before, frozen = source_state(document), deepcopy(steps)
    result = workflows.run(document, steps, gaussian_rebind=ij.TargetRequest(
        roi=ij.RoiPolicy.WHOLE_PLANE, destination=destination))
    np.testing.assert_array_equal(result, np.array([[77, 178]], np.uint8))
    assert result.dtype == np.uint8
    assert_source_unchanged(document, before)
    assert steps == frozen
    result[0, 0] = 99
    assert_source_unchanged(document, before)


def test_h3_w04_scaled_intent_uses_destination_full_calibration():
    document = Document(np.array([[0, 255]], np.uint8))
    document.set_calibration(Calibration(
        pixel_width=0.5, pixel_height=2, pixel_depth=3, unit="µm",
        origin=(11, -7, 5), direction=(0, -1, 0, 1, 0, 0, 0, 0, 1),
        frame_interval=0.25, time_origin=8, time_unit="min"))
    # The original pixel-unit record has sigma0.5 in both axes. Explicit rebind
    # uses destination spacing to produce sigmaX1, sigmaY0.25; this one-row
    # fixture has the independently fixed horizontal sigma1 output.
    steps = [raw_record(sigma=0.5, scaled_units=True)]
    assert steps[0]["calibration"]["unit"] == "px"
    assert steps[0]["effective_sigma_xy"] == [0.5, 0.5]
    before, frozen = source_state(document), deepcopy(steps)
    result = workflows.run(document, steps, gaussian_rebind=ij.TargetRequest(
        roi=ij.RoiPolicy.WHOLE_PLANE))
    np.testing.assert_array_equal(result, np.array([[77, 178]], np.uint8))
    assert_source_unchanged(document, before)
    assert steps == frozen


