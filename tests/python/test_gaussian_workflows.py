@pytest.fixture
def editor(tmp_path):
    if os.environ.get("IMAGEJXX_REQUIRE_RENDER_TESTS") == "1":
        importlib.import_module("imagejxx._desktop")
    else:
        pytest.importorskip("imagejxx._desktop", exc_type=ModuleNotFoundError)
    from imagejxx.ui.app import Editor
    from imagejxx.ui.persistence import Preferences
    return Editor(preferences=Preferences(tmp_path / "gaussian-workflow-prefs.json"))


def test_h3_w15_cpp_runner_requires_explicit_rebind_and_preserves_failed_source(editor):
    editor.add_document(np.array([[0, 255]], np.uint8))
    steps = [raw_record()]
    editor.workflow = steps
    live = editor.live_document()
    owner = live.native_owner
    history_before = (owner.undo_steps, owner.redo_steps)
    before = live.native_snapshot()
    with pytest.raises((ValueError, RuntimeError), match="explicit TargetRequest"):
        editor.action("run_workflow")
        editor.wait()
    after = live.native_snapshot()
    assert before.shares_data(after)
    assert (owner.undo_steps, owner.redo_steps) == history_before
    assert editor.workflow == steps


@pytest.mark.parametrize("rebind_request", [{}, {"roi": "whole_plane"},
                                     {"roi": "whole_plane", "destination": "new_document"}],
                         ids=["explicit-default", "whole-plane", "new-document-scratch"])
def test_h3_w16_cpp_runner_rebinds_only_explicit_choice_and_publishes_once(editor, rebind_request):
    editor.add_document(np.array([[0, 255]], np.uint8))
    steps = [{"operation": "invert", "parameters": {}}, raw_record()]
    editor.workflow = steps
    live = editor.live_document()
    owner = live.native_owner
    undo_before = owner.undo_steps
    before = live.native_snapshot()
    editor.action("run_workflow", gaussian_rebind=rebind_request)
    editor.wait()
    np.testing.assert_array_equal(editor.document.data, np.array([[178, 77]], np.uint8))
    assert owner.undo_steps == undo_before + 1 and owner.redo_steps == 0
    assert editor.workflow == steps
    owner.undo()
    assert owner.snapshot().dataset.numpy("YX").tobytes() == before.dataset.numpy("YX").tobytes()
    assert owner.undo_steps == undo_before and owner.redo_steps == 1


