def test_h3_w08_mixed_numeric_and_typed_steps_keep_dispatch_and_progress_order():
    document = Document(np.array([[0, 255]], np.uint8))
    steps = [
        {"operation": "invert", "parameters": {}},
        raw_record(),
        {"operation": "subtract", "parameters": {"value": 1}},
    ]
    before, frozen, progress = source_state(document), deepcopy(steps), []
    result = workflows.run(document, workflows.loads(workflows.dumps(steps)),
                           gaussian_rebind=ij.TargetRequest(roi=ij.RoiPolicy.WHOLE_PLANE),
                           progress=lambda i, total: progress.append((i, total)))
    np.testing.assert_array_equal(result, np.array([[177, 76]], np.uint8))
    assert progress == [(1, 3), (2, 3), (3, 3)]
    assert_source_unchanged(document, before)
    assert steps == frozen


