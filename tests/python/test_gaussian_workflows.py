MALFORMED_RECORDS = [
    (("schema_version",), True),
    (("schema_version",), 2),
    (("parameters",), {}),
    (("options", "scaled_units"), "false"),
    (("effective_sigma_xy",), [2.0, 2.0]),
    (("calibration", "unit"), ""),
    (("target", "document_id"), True),
    (("target", "source_revisions"), [0.0, 0, 0]),
    (("target", "source_shape"), [1, 1, 1, 1, 0, 1]),
    (("target", "ranges"), [[0, 1, 1], [0, 1, 1], [0, 2, 1]]),
]


def mutated_record(path, value):
    record = raw_record()
    node = record
    for name in path[:-1]:
        node = node[name]
    node[path[-1]] = deepcopy(value)
    return record


@pytest.mark.parametrize("path,value", MALFORMED_RECORDS,
                         ids=["boolean-schema", "unknown-schema", "mixed-raw-legacy",
                              "boolean-option-coercion", "effective-contradiction",
                              "invalid-calibration", "boolean-source-id",
                              "floating-revision", "zero-original-shape",
                              "original-range-outside"])
@pytest.mark.parametrize("entrypoint", ["validate", "dumps", "loads", "run"])
def test_h3_w10_malformed_typed_records_reject_before_any_step_or_source_publication(
        path, value, entrypoint):
    document = Document(np.array([[0, 255]], np.uint8))
    steps = [{"operation": "invert", "parameters": {}}, mutated_record(path, value)]
    before, frozen, progress = source_state(document), deepcopy(steps), []
    with pytest.raises((ValueError, TypeError, OverflowError, IndexError)):
        if entrypoint == "validate":
            workflows.validate_steps(steps)
        elif entrypoint == "dumps":
            workflows.dumps(steps)
        elif entrypoint == "loads":
            workflows.loads(json.dumps({"format": "imagejxx-workflow", "version": 1,
                                        "steps": steps}))
        else:
            workflows.run(document, steps, gaussian_rebind=ij.TargetRequest(),
                          progress=lambda i, total: progress.append((i, total)))
    assert_source_unchanged(document, before)
    assert steps == frozen and progress == []


def test_h3_w11_later_legacy_failure_discards_an_already_computed_typed_proposal():
    document = Document(np.array([[0, 255]], np.uint8))
    steps = [raw_record(), {"operation": "add", "parameters": {"value": 1},
                           "slice_index": 99}]
